package codegen

import (
	"regexp"
	"strings"

	"github.com/t4wefan/meshcall/meshcall-router/internal/contract"
)

// PythonOptions configures Python client generation.
type PythonOptions struct {
	ClassName           string
	MeshcallRequirement string // default "meshcall>=0.1.0"
	PydanticRequirement string // default "pydantic>=2.11"
	ModelsImport        string // package module only; default ".models"
}

func (o PythonOptions) withDefaults() PythonOptions {
	if o.MeshcallRequirement == "" {
		o.MeshcallRequirement = "meshcall>=0.1.0"
	}
	if o.PydanticRequirement == "" {
		o.PydanticRequirement = "pydantic>=2.11"
	}
	if o.ModelsImport == "" {
		o.ModelsImport = ".models"
	}
	return o
}

// PythonClientClassName is the default client class: <Qualname>Client.
func PythonClientClassName(service *contract.Service) string {
	return pyClassName(lastSegment(service.SourceQualname), "Service") + "Client"
}

// PythonTypeNames lists the model names a generated package exports.
func PythonTypeNames(service *contract.Service) []string {
	return newTypeRegistry(service, pyClassName).TypeNames()
}

// RenderPythonClient renders one self-contained module: models and client.
func RenderPythonClient(service *contract.Service, opts PythonOptions) string {
	opts = opts.withDefaults()
	registry := newTypeRegistry(service, pyClassName)
	modelLines := renderPythonModelDeclarations(registry)
	lines := []string{
		"# Generated by MeshCall from a portable contract. Do not edit manually.",
		"# External dependencies: uv add " + pyStringRepr(opts.MeshcallRequirement) + " " + pyStringRepr(opts.PydanticRequirement),
		"from __future__ import annotations",
	}
	lines = append(lines, "", pyAbcImportLine(service))
	lines = append(lines, pyModelImportLines(modelLines)...)
	lines = append(lines, "", "from meshcall.client import ClientBase")
	if imports := pyStreamImports(service); len(imports) > 0 {
		lines = append(lines, "from meshcall.streams import "+strings.Join(imports, ", "))
	}
	lines = append(lines, "", "")
	lines = append(lines, modelLines...)
	lines = append(lines, "", "")
	className := opts.ClassName
	if className == "" {
		className = PythonClientClassName(service)
	}
	lines = append(lines, renderPythonClientClass(service, registry, className)...)
	return strings.Join(lines, "\n") + "\n"
}

// RenderPythonModels renders the models module of a package.
func RenderPythonModels(service *contract.Service) string {
	registry := newTypeRegistry(service, pyClassName)
	modelLines := renderPythonModelDeclarations(registry)
	lines := []string{
		"# Generated by MeshCall from a portable contract. Do not edit manually.",
		"from __future__ import annotations",
	}
	lines = append(lines, pyModelImportLines(modelLines)...)
	lines = append(lines, "", "")
	lines = append(lines, modelLines...)
	return strings.TrimRight(strings.Join(lines, "\n"), "\n") + "\n"
}

// RenderPythonClientModule renders the client module of a package.
func RenderPythonClientModule(service *contract.Service, opts PythonOptions) string {
	opts = opts.withDefaults()
	registry := newTypeRegistry(service, pyClassName)
	lines := []string{
		"# Generated by MeshCall from a portable contract. Do not edit manually.",
		"from __future__ import annotations",
	}
	lines = append(lines, "", pyAbcImportLine(service))
	lines = append(lines, "", "from meshcall.client import ClientBase")
	if imports := pyStreamImports(service); len(imports) > 0 {
		lines = append(lines, "from meshcall.streams import "+strings.Join(imports, ", "))
	}
	lines = append(lines, "", "from "+opts.ModelsImport+" import "+strings.Join(registry.TypeNames(), ", "), "", "")
	className := opts.ClassName
	if className == "" {
		className = PythonClientClassName(service)
	}
	lines = append(lines, renderPythonClientClass(service, registry, className)...)
	return strings.Join(lines, "\n") + "\n"
}

func pyAbcImportLine(service *contract.Service) string {
	names := []string{"Mapping"}
	if hasStream(service, "client_stream") {
		names = append([]string{"AsyncIterable"}, names...)
	}
	return "from collections.abc import " + strings.Join(names, ", ")
}

func pyStreamImports(service *contract.Service) []string {
	var imports []string
	if hasStream(service, "duplex") {
		imports = append(imports, "RpcDuplexClient")
	}
	if hasStream(service, "server_stream") {
		imports = append(imports, "RpcServerStream")
	}
	return imports
}

func renderPythonClientClass(service *contract.Service, registry *typeRegistry, className string) []string {
	lines := []string{"class " + className + "(ClientBase):"}
	lines = append(lines, pyDocstringLines(service.Description, "    ")...)
	lines = append(lines, "    service_name = "+pyStringRepr(service.Name))
	instanceParam := "        instance: str | None = None,"
	if service.Targeted {
		instanceParam = "        instance: str,"
	}
	for _, m := range service.Methods {
		request := registry.Name(m.Request)
		params := pyParameters(m, registry)
		lines = append(lines, "")
		var idempotent []string
		if m.Annotations.Idempotent {
			idempotent = []string{"            idempotent=True,"}
		}
		tail := func(call string, args ...string) []string {
			out := []string{call, "            self.service_name,", "            " + pyStringRepr(m.Name) + ",", "            request,"}
			for _, a := range args {
				out = append(out, "            "+a+",")
			}
			out = append(out,
				"            timeout=timeout,",
				"            idle_timeout=idle_timeout,",
				"            metadata=metadata,",
				"            instance=instance,")
			out = append(out, idempotent...)
			return append(out, "        )")
		}
		kwargs := func() []string {
			return []string{
				"        *,",
				instanceParam,
				"        timeout: float | None = None,",
				"        idle_timeout: float | None = None,",
				"        metadata: Mapping[str, str] | None = None,",
			}
		}
		indented := func(items []string) []string {
			out := make([]string, len(items))
			for i, p := range items {
				out[i] = "        " + p + ","
			}
			return out
		}
		switch m.Stream {
		case "unary":
			response := registry.Name(requiredRef(m.Response, m.Name+" response"))
			lines = append(lines, "    async def "+m.Name+"(", "        self,")
			lines = append(lines, indented(params)...)
			lines = append(lines, kwargs()...)
			lines = append(lines, "    ) -> "+response+":")
			lines = append(lines, pyDocstringLines(m.Description, "        ")...)
			lines = append(lines, pyRequestLines(m, request)...)
			lines = append(lines, tail("        return await self.call_unary(", response)...)
		case "server_stream":
			output := registry.Name(requiredRef(m.OutputItem, m.Name+" output item"))
			lines = append(lines, "    def "+m.Name+"(", "        self,")
			lines = append(lines, indented(params)...)
			lines = append(lines, kwargs()...)
			lines = append(lines, "    ) -> RpcServerStream["+output+"]:")
			lines = append(lines, pyDocstringLines(m.Description, "        ")...)
			lines = append(lines, pyRequestLines(m, request)...)
			lines = append(lines, tail("        return self.call_server_stream(", output)...)
		case "client_stream":
			input := registry.Name(requiredRef(m.InputItem, m.Name+" input item"))
			response := registry.Name(requiredRef(m.Response, m.Name+" response"))
			lines = append(lines, "    async def "+m.Name+"(", "        self,")
			// The stream comes first: it is always required, while parameters may carry defaults.
			lines = append(lines, "        items: AsyncIterable["+input+"],")
			lines = append(lines, indented(params)...)
			lines = append(lines, kwargs()...)
			lines = append(lines, "    ) -> "+response+":")
			lines = append(lines, pyDocstringLines(m.Description, "        ")...)
			lines = append(lines, pyRequestLines(m, request)...)
			lines = append(lines, tail("        return await self.call_client_stream(", "items", input, response)...)
		default: // duplex
			input := registry.Name(requiredRef(m.InputItem, m.Name+" input item"))
			output := registry.Name(requiredRef(m.OutputItem, m.Name+" output item"))
			result := "None"
			if m.Response != nil {
				result = registry.Name(m.Response)
			}
			lines = append(lines, "    def "+m.Name+"(", "        self,")
			lines = append(lines, indented(params)...)
			lines = append(lines, kwargs()...)
			lines = append(lines, "    ) -> RpcDuplexClient["+input+", "+output+", "+result+"]:")
			lines = append(lines, pyDocstringLines(m.Description, "        ")...)
			lines = append(lines, pyRequestLines(m, request)...)
			lines = append(lines, tail("        return self.call_duplex(", input, output, result)...)
		}
	}
	return lines
}

func pyDocstringLines(text *string, indent string) []string {
	if text == nil || *text == "" {
		return nil
	}
	body := strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(*text), "\\", "\\\\"), `"""`, `\"\"\"`)
	if !strings.Contains(body, "\n") {
		return []string{indent + `"""` + body + `"""`}
	}
	parts := strings.Split(body, "\n")
	lines := []string{indent + `"""` + parts[0]}
	for _, p := range parts[1:] {
		lines = append(lines, strings.TrimRight(indent+p, " \t"))
	}
	return append(lines, indent+`"""`)
}

func pyParameters(m *contract.Method, registry *typeRegistry) []string {
	properties := m.Request.Schema.Obj("properties")
	required := stringSet(m.Request.Schema.Strings("required"))
	defNames := registry.DefinitionNames(m.Request)
	var params []string
	for _, field := range m.Parameters {
		prop := properties.Obj(field)
		if prop == nil {
			panic(genError("Request parameter " + pyStringRepr(field) + " is missing from " + m.Request.Qualname))
		}
		t := pyType(prop, defNames)
		switch {
		case required[field]:
			params = append(params, field+": "+t)
		case prop.Has("default"):
			params = append(params, field+": "+t+" = "+pyRepr(prop.Values["default"]))
		default:
			params = append(params, field+": "+t+" | None = None")
		}
	}
	return params
}

func pyRequestLines(m *contract.Method, requestName string) []string {
	if len(m.Parameters) == 0 {
		return []string{"        request = " + requestName + "()"}
	}
	lines := []string{"        request = " + requestName + "("}
	for _, field := range m.Parameters {
		lines = append(lines, "            "+field+"="+field+",")
	}
	return append(lines, "        )")
}

func renderPythonModelDeclarations(registry *typeRegistry) []string {
	var lines []string
	for _, ref := range registry.refs {
		names := registry.DefinitionNames(ref)
		if defs := ref.Schema.Obj("$defs"); defs != nil {
			for _, key := range defs.Keys {
				block := renderPythonModel(names[key], defs.Obj(key), names)
				if !pyRenderedHeads(lines)[block[0]] {
					if len(lines) > 0 {
						lines = append(lines, "", "")
					}
					lines = append(lines, block...)
				}
			}
		}
		if len(lines) > 0 {
			lines = append(lines, "", "")
		}
		lines = append(lines, renderPythonModel(registry.Name(ref), ref.Schema, names)...)
	}
	return lines
}

func pyRenderedHeads(lines []string) map[string]bool {
	heads := map[string]bool{}
	for _, line := range lines {
		if strings.HasPrefix(line, "class ") || strings.HasPrefix(line, "type ") ||
			(strings.Contains(line, " = ") && !strings.HasPrefix(line, " ")) {
			heads[line] = true
		}
	}
	return heads
}

func pyModelImportLines(modelLines []string) []string {
	var typing []string
	for _, name := range []string{"Any", "Literal"} {
		re := regexp.MustCompile(`\b` + name + `\b`)
		for _, line := range modelLines {
			if re.MatchString(line) {
				typing = append(typing, name)
				break
			}
		}
	}
	pydantic := []string{"BaseModel"}
	for _, line := range modelLines {
		if strings.Contains(line, "Field(") {
			pydantic = append(pydantic, "Field")
			break
		}
	}
	var lines []string
	if len(typing) > 0 {
		lines = append(lines, "", "from typing import "+strings.Join(typing, ", "))
	}
	return append(lines, "", "from pydantic import "+strings.Join(pydantic, ", "))
}

func renderPythonModel(name string, schema *contract.Object, defNames map[string]string) []string {
	if schema.Has("enum") || schema.Has("const") {
		return []string{name + " = " + pyType(schema, defNames)}
	}
	if schema.Str("type") != "object" && !schema.Has("properties") {
		panic(genError("Portable Python model " + name + " must use an object schema"))
	}
	required := stringSet(schema.Strings("required"))
	properties := schema.Obj("properties")
	lines := []string{"class " + name + "(BaseModel):"}
	if properties == nil || len(properties.Keys) == 0 {
		return append(lines, "    pass")
	}
	for _, propName := range properties.Keys {
		prop := properties.Obj(propName)
		fieldName := pyFieldName(propName)
		fieldType := pyType(prop, defNames)
		isRequired := required[propName]
		if !isRequired && !prop.Has("default") {
			fieldType += " | None"
		}
		def := ""
		if !isRequired {
			def = " = " + pyRepr(prop.Values["default"]) // absent → None
		}
		if fieldName != propName {
			fieldDefault := "..."
			if !isRequired {
				fieldDefault = pyRepr(prop.Values["default"])
			}
			def = " = Field(" + fieldDefault + ", alias=" + pyStringRepr(propName) + ")"
		}
		lines = append(lines, "    "+fieldName+": "+fieldType+def)
	}
	return lines
}

func pyType(schema *contract.Object, defNames map[string]string) string {
	if ref := schema.Str("$ref"); strings.HasPrefix(ref, "#/$defs/") {
		key := ref[strings.LastIndexByte(ref, '/')+1:]
		if name, ok := defNames[key]; ok {
			return name
		}
		return pyClassName(key, "Any")
	}
	if schema.Has("const") {
		return "Literal[" + pyRepr(schema.Values["const"]) + "]"
	}
	if enum, ok := schema.Values["enum"].([]any); ok && len(enum) > 0 {
		values := make([]string, len(enum))
		for i, v := range enum {
			values[i] = pyRepr(v)
		}
		return "Literal[" + strings.Join(values, ", ") + "]"
	}
	for _, keyword := range []string{"anyOf", "oneOf"} {
		if variants, ok := schema.Values[keyword].([]any); ok && len(variants) > 0 {
			return joinTypes(variants, defNames, pyType, " | ")
		}
	}
	switch t := schema.Values["type"].(type) {
	case []any:
		parts := make([]string, len(t))
		for i, item := range t {
			parts[i] = pyType(schema.With("type", item), defNames)
		}
		return strings.Join(parts, " | ")
	case string:
		switch t {
		case "integer":
			return "int"
		case "number":
			return "float"
		case "string":
			return "str"
		case "boolean":
			return "bool"
		case "null":
			return "None"
		case "array":
			items := schema.Obj("items")
			if items == nil {
				items = &contract.Object{}
			}
			return "list[" + pyType(items, defNames) + "]"
		case "object":
			valueType := "Any"
			switch additional := schema.Values["additionalProperties"].(type) {
			case *contract.Object:
				valueType = pyType(additional, defNames)
			case nil:
				valueType = pyType(&contract.Object{}, defNames)
			}
			return "dict[str, " + valueType + "]"
		}
	}
	return "Any"
}

func joinTypes(variants []any, defNames map[string]string, render func(*contract.Object, map[string]string) string, sep string) string {
	parts := make([]string, 0, len(variants))
	for _, v := range variants {
		obj, _ := v.(*contract.Object)
		if obj == nil {
			obj = &contract.Object{}
		}
		parts = append(parts, render(obj, defNames))
	}
	return strings.Join(parts, sep)
}

var nonWord = regexp.MustCompile(`\W`)
var nonIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

var pyKeywords = stringSet(strings.Fields(`False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield`))

func pyFieldName(value string) string {
	identifier := nonWord.ReplaceAllString(value, "_")
	if identifier == "" || (identifier[0] >= '0' && identifier[0] <= '9') {
		identifier = "field_" + identifier
	}
	if pyKeywords[identifier] {
		identifier += "_"
	}
	return identifier
}

func pyClassName(value, fallback string) string {
	identifier := nonIdent.ReplaceAllString(value, "_")
	if identifier == "" {
		return fallback
	}
	if identifier[0] >= '0' && identifier[0] <= '9' {
		return "Model_" + identifier
	}
	return identifier
}

func stringSet(items []string) map[string]bool {
	set := make(map[string]bool, len(items))
	for _, item := range items {
		set[item] = true
	}
	return set
}
