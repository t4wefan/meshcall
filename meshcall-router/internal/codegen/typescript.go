package codegen

import (
	"regexp"
	"strings"

	"github.com/t4wefan/meshcall/meshcall-router/internal/contract"
)

// TypeScriptOptions configures TypeScript client generation.
type TypeScriptOptions struct {
	ClassName      string
	RuntimeImport  string // default "meshcall"
	RuntimeVersion string // default "^0.1.0"
	ModelsImport   string // package module only; default "./models.js"
}

func (o TypeScriptOptions) withDefaults() TypeScriptOptions {
	if o.RuntimeImport == "" {
		o.RuntimeImport = "meshcall"
	}
	if o.RuntimeVersion == "" {
		o.RuntimeVersion = "^0.1.0"
	}
	if o.ModelsImport == "" {
		o.ModelsImport = "./models.js"
	}
	return o
}

// TypeScriptClientClassName is the default client class: <Qualname>Client.
func TypeScriptClientClassName(service *contract.Service) string {
	return tsIdentifier(lastSegment(service.SourceQualname), "Service") + "Client"
}

// TypeScriptTypeNames lists the interface/type names a generated package exports.
func TypeScriptTypeNames(service *contract.Service) []string {
	return newTypeRegistry(service, tsIdentifier).TypeNames()
}

// RenderTypeScriptClient renders one self-contained module: types and client.
func RenderTypeScriptClient(service *contract.Service, opts TypeScriptOptions) (string, error) {
	if err := requireTypeScriptStreams(service); err != nil {
		return "", err
	}
	opts = opts.withDefaults()
	registry := newTypeRegistry(service, tsIdentifier)
	received := receivedTypes(service, registry)
	runtime := tsRuntimeTypes(service)
	if len(received) > 0 {
		runtime += ", type JsonSchema"
	}
	lines := []string{
		"// Generated by MeshCall. Do not edit manually.",
		"// External dependency: yarn add " + opts.RuntimeImport + "@" + opts.RuntimeVersion,
		"import { " + runtime + " } from " + jsonDumps(opts.RuntimeImport) + ";",
		"",
	}
	lines = append(lines, renderTypeScriptDeclarations(registry, received)...)
	className := opts.ClassName
	if className == "" {
		className = TypeScriptClientClassName(service)
	}
	lines = append(lines, renderTypeScriptClientClass(service, registry, className)...)
	return strings.Join(lines, "\n"), nil
}

// RenderTypeScriptModels renders the models module of a package.
func RenderTypeScriptModels(service *contract.Service, opts TypeScriptOptions) (string, error) {
	if err := requireTypeScriptStreams(service); err != nil {
		return "", err
	}
	opts = opts.withDefaults()
	registry := newTypeRegistry(service, tsIdentifier)
	received := receivedTypes(service, registry)
	lines := []string{"// Generated by MeshCall. Do not edit manually."}
	if len(received) > 0 {
		lines = append(lines, "import type { JsonSchema } from "+jsonDumps(opts.RuntimeImport)+";")
	}
	lines = append(lines, "")
	lines = append(lines, renderTypeScriptDeclarations(registry, received)...)
	return strings.Join(lines, "\n"), nil
}

// RenderTypeScriptClientModule renders the client module of a package.
func RenderTypeScriptClientModule(service *contract.Service, opts TypeScriptOptions) (string, error) {
	if err := requireTypeScriptStreams(service); err != nil {
		return "", err
	}
	opts = opts.withDefaults()
	registry := newTypeRegistry(service, tsIdentifier)
	lines := []string{
		"// Generated by MeshCall. Do not edit manually.",
		"import { " + tsRuntimeTypes(service) + " } from " + jsonDumps(opts.RuntimeImport) + ";",
		"import type { " + strings.Join(registry.TypeNames(), ", ") + " } from " + jsonDumps(opts.ModelsImport) + ";",
	}
	if received := receivedTypes(service, registry); len(received) > 0 {
		names := make([]string, 0, len(received))
		for _, name := range registry.TypeNames() {
			if received[name] {
				names = append(names, name+"Schema")
			}
		}
		lines = append(lines, "import { "+strings.Join(names, ", ")+" } from "+jsonDumps(opts.ModelsImport)+";")
	}
	lines = append(lines, "")
	className := opts.ClassName
	if className == "" {
		className = TypeScriptClientClassName(service)
	}
	lines = append(lines, renderTypeScriptClientClass(service, registry, className)...)
	return strings.Join(lines, "\n"), nil
}

// receivedTypes names the root types a client receives (responses and output
// items); their schemas are emitted so the client can validate locally.
func receivedTypes(service *contract.Service, registry *typeRegistry) map[string]bool {
	out := map[string]bool{}
	for _, m := range service.Methods {
		if m.Response != nil {
			out[registry.Name(m.Response)] = true
		}
		if m.OutputItem != nil {
			out[registry.Name(m.OutputItem)] = true
		}
	}
	return out
}

func renderTypeScriptDeclarations(registry *typeRegistry, received map[string]bool) []string {
	var lines []string
	rendered := map[string]bool{}
	for _, ref := range registry.refs {
		names := registry.DefinitionNames(ref)
		if defs := ref.Schema.Obj("$defs"); defs != nil {
			for _, key := range defs.Keys {
				if rendered[names[key]] {
					continue
				}
				rendered[names[key]] = true
				lines = append(lines, renderTypeScriptDeclaration(names[key], defs.Obj(key), names)...)
				lines = append(lines, "")
			}
		}
		name := registry.Name(ref)
		lines = append(lines, renderTypeScriptDeclaration(name, ref.Schema, names)...)
		lines = append(lines, "")
		if received[name] {
			lines = append(lines, "export const "+name+"Schema: JsonSchema = "+jsonDumpsIndent(ref.Schema, 2)+";", "")
		}
	}
	return lines
}

func renderTypeScriptClientClass(service *contract.Service, registry *typeRegistry, className string) []string {
	lines := tsDocLines(service.Description, "")
	lines = append(lines,
		"export class "+className+" {",
		"  public constructor(private readonly rpc: MeshCallClient) {}")
	for _, m := range service.Methods {
		request := registry.Name(m.Request)
		var resultType, rpcCall string
		var extraParams, extraArgs []string
		switch m.Stream {
		case "unary":
			response := registry.Name(requiredRef(m.Response, "response"))
			resultType = "Promise<" + response + ">"
			rpcCall = "unary<" + request + ", " + response + ">"
		case "server_stream":
			output := registry.Name(requiredRef(m.OutputItem, "server stream item"))
			resultType = "MeshCallServerStream<" + output + ">"
			rpcCall = "serverStream<" + request + ", " + output + ">"
		case "client_stream":
			input := registry.Name(requiredRef(m.InputItem, "client stream item"))
			response := registry.Name(requiredRef(m.Response, "response"))
			resultType = "Promise<" + response + ">"
			rpcCall = "clientStream<" + request + ", " + input + ", " + response + ">"
			extraParams = []string{"items: AsyncIterable<" + input + ">"}
			extraArgs = []string{"      items,"}
		}
		lines = append(lines, "")
		lines = append(lines, tsDocLines(m.Description, "  ")...)
		lines = append(lines, "  public "+m.Name+"(")
		// The input stream comes first: always required, unlike parameters with defaults.
		for _, p := range extraParams {
			lines = append(lines, "    "+p+",")
		}
		for _, p := range tsParameters(m, registry) {
			lines = append(lines, "    "+p+",")
		}
		if service.Targeted {
			lines = append(lines, "    options: CallOptions & { instance: string },")
		} else {
			lines = append(lines, "    options?: CallOptions,")
		}
		lines = append(lines,
			"  ): "+resultType+" {",
			"    return this.rpc."+rpcCall+"(",
			"      "+jsonDumps(service.Name)+",",
			"      "+jsonDumps(m.Name)+",")
		lines = append(lines, tsPayload(m)...)
		lines = append(lines, extraArgs...)
		var fields []string
		if m.Annotations.Idempotent {
			fields = append(fields, "idempotent: true")
		}
		fields = append(fields, "...options")
		switch m.Stream {
		case "server_stream":
			fields = append(fields, "itemSchema: "+registry.Name(m.OutputItem)+"Schema")
		default:
			fields = append(fields, "responseSchema: "+registry.Name(m.Response)+"Schema")
		}
		lines = append(lines, "      { "+strings.Join(fields, ", ")+" },")
		lines = append(lines, "    );", "  }")
	}
	return append(lines, "}", "")
}

func tsDocLines(text *string, indent string) []string {
	if text == nil || *text == "" {
		return nil
	}
	body := strings.ReplaceAll(strings.TrimSpace(*text), "*/", "*\\/")
	lines := []string{indent + "/**"}
	for _, line := range strings.Split(body, "\n") {
		lines = append(lines, strings.TrimRight(indent+" * "+line, " \t"))
	}
	return append(lines, indent+" */")
}

var tsIdentifierRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsParameters(m *contract.Method, registry *typeRegistry) []string {
	properties := m.Request.Schema.Obj("properties")
	required := stringSet(m.Request.Schema.Strings("required"))
	defNames := registry.DefinitionNames(m.Request)
	var params []string
	for _, field := range m.Parameters {
		if !tsIdentifierRe.MatchString(field) {
			panic(genError("Request parameter " + pyStringRepr(field) + " is not a valid TypeScript parameter name"))
		}
		prop := properties.Obj(field)
		if prop == nil {
			panic(genError("Request parameter " + pyStringRepr(field) + " is missing from " + m.Request.Qualname))
		}
		t := tsType(prop, defNames)
		switch {
		case required[field]:
			params = append(params, field+": "+t)
		case prop.Has("default"):
			params = append(params, field+": "+t+" = "+jsonDumps(prop.Values["default"]))
		default:
			params = append(params, field+"?: "+t)
		}
	}
	return params
}

func tsPayload(m *contract.Method) []string {
	if len(m.Parameters) == 0 {
		return []string{"      {},"}
	}
	lines := []string{"      {"}
	for _, field := range m.Parameters {
		lines = append(lines, "        "+tsProperty(field)+": "+field+",")
	}
	return append(lines, "      },")
}

func renderTypeScriptDeclaration(name string, schema *contract.Object, defNames map[string]string) []string {
	if schema.Str("type") == "object" || schema.Has("properties") {
		required := stringSet(schema.Strings("required"))
		lines := []string{"export interface " + name + " {"}
		if properties := schema.Obj("properties"); properties != nil {
			for _, propName := range properties.Keys {
				optional := "?"
				if required[propName] {
					optional = ""
				}
				lines = append(lines, "  "+tsProperty(propName)+optional+": "+tsType(properties.Obj(propName), defNames)+";")
			}
		}
		switch additional := schema.Values["additionalProperties"].(type) {
		case bool:
			if additional {
				lines = append(lines, "  [key: string]: unknown;")
			}
		case *contract.Object:
			lines = append(lines, "  [key: string]: "+tsType(additional, defNames)+";")
		}
		return append(lines, "}")
	}
	return []string{"export type " + name + " = " + tsType(schema, defNames) + ";"}
}

func tsType(schema *contract.Object, defNames map[string]string) string {
	if ref := schema.Str("$ref"); strings.HasPrefix(ref, "#/$defs/") {
		key := ref[strings.LastIndexByte(ref, '/')+1:]
		if name, ok := defNames[key]; ok {
			return name
		}
		return tsIdentifier(key, "unknown")
	}
	if schema.Has("const") {
		return jsonDumps(schema.Values["const"])
	}
	if enum, ok := schema.Values["enum"].([]any); ok && len(enum) > 0 {
		values := make([]string, len(enum))
		for i, v := range enum {
			values[i] = jsonDumps(v)
		}
		return strings.Join(values, " | ")
	}
	for _, keyword := range []string{"anyOf", "oneOf"} {
		if variants, ok := schema.Values[keyword].([]any); ok && len(variants) > 0 {
			return joinTypes(variants, defNames, tsType, " | ")
		}
	}
	if allOf, ok := schema.Values["allOf"].([]any); ok && len(allOf) > 0 {
		return joinTypes(allOf, defNames, tsType, " & ")
	}
	switch t := schema.Values["type"].(type) {
	case []any:
		parts := make([]string, len(t))
		for i, item := range t {
			parts[i] = tsType(schema.With("type", item), defNames)
		}
		return strings.Join(parts, " | ")
	case string:
		switch t {
		case "integer", "number":
			return "number"
		case "string":
			return "string"
		case "boolean":
			return "boolean"
		case "null":
			return "null"
		case "array":
			items := schema.Obj("items")
			if items == nil {
				items = &contract.Object{}
			}
			return "Array<" + tsType(items, defNames) + ">"
		case "object":
			valueType := "unknown"
			switch additional := schema.Values["additionalProperties"].(type) {
			case *contract.Object:
				valueType = tsType(additional, defNames)
			case nil:
				valueType = tsType(&contract.Object{}, defNames)
			}
			return "Record<string, " + valueType + ">"
		}
	}
	return "unknown"
}

func tsProperty(name string) string {
	if tsIdentifierRe.MatchString(name) {
		return name
	}
	return jsonDumps(name)
}

var tsNonIdent = regexp.MustCompile(`[^A-Za-z0-9_$]`)

func tsIdentifier(value, fallback string) string {
	identifier := tsNonIdent.ReplaceAllString(value, "_")
	if identifier == "" {
		return fallback
	}
	if identifier[0] >= '0' && identifier[0] <= '9' {
		return "_" + identifier
	}
	return identifier
}

func tsRuntimeTypes(service *contract.Service) string {
	names := []string{"MeshCallClient", "type CallOptions"}
	if hasStream(service, "server_stream") {
		names = append(names, "type MeshCallServerStream")
	}
	return strings.Join(names, ", ")
}

func requireTypeScriptStreams(service *contract.Service) error {
	var unsupported []string
	for _, m := range service.Methods {
		if m.Stream == "duplex" {
			unsupported = append(unsupported, m.Name)
		}
	}
	if len(unsupported) > 0 {
		return genError("TypeScript generation does not expose experimental duplex methods: " + strings.Join(unsupported, ", "))
	}
	return nil
}
